@dataclass(frozen=True)
class GenerationArguments:
    values: dict[str, Any]

    @classmethod
    def from_positional(cls, args):
        if len(args) != len(GENERATION_FIELDS):
            raise ValueError(
                f"Expected {len(GENERATION_FIELDS)} generation inputs, received {len(args)}."
            )
        return cls(dict(zip(GENERATION_FIELDS, args, strict=True)))

    @property
    def references(self):
        return {
            kind: tuple(self.values[f"ref_{kind}_{i}"] for i in range(1, count + 1))
            for kind, count in (("image", 9), ("video", 3), ("audio", 3))
        }

    def with_seed(self, seed):
        return replace(self, values={**self.values, "seed": seed})
